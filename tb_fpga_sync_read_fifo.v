// ============================================================================
// Purpose:
// Verify the functionality of an FPGA-oriented synchronous-read FIFO.
//
// Test Coverage:
// 1. Synchronous reset.
// 2. Basic write and read operations.
// 3. FIFO data ordering.
// 4. Synchronous memory read behavior.
// 5. Full and empty conditions.
// 6. Simultaneous read/write operations.
// 7. Write and read pointer wraparound.
// 8. Rejected writes when FIFO is full.
// 9. Rejected reads when FIFO is empty.
// 10. Occupancy counter verification.
// 11. data_valid behavior (high after accepted read, low otherwise).
//
// Important Note:
// The DUT registers data_out on the same clock edge as an accepted read.
// Therefore, the testbench checks the output after the nonblocking
// assignments have updated.
//
// ============================================================================


module tb_fpga_sync_read_fifo;

    // ========================================================================
    // 1. PARAMETERS
    // ========================================================================

    parameter DATA_WIDTH  = 8;   // Number of bits in each FIFO data word.
    parameter DEPTH       = 16;  // Total number of words the FIFO can store.
    parameter ADDR_WIDTH  = 4;   // Address width required for 16 memory locations.
    parameter COUNT_WIDTH = 5;   // Five bits represent occupancy from 0 to 16.


    // ========================================================================
    // 2. TESTBENCH SIGNAL DECLARATIONS
    // ========================================================================

    reg clk;                     // Clock signal generated by the testbench.
    reg rst;                     // Synchronous active-high reset.

    reg wr_en;                   // Write enable: requests a FIFO write.
    reg [DATA_WIDTH-1:0] data_in; // Input data bus connected to the FIFO.

    reg rd_en;                   // Read enable: requests a FIFO read.

    wire [DATA_WIDTH-1:0] data_out; // Registered FIFO output data.

    wire data_valid;             // High when data_out holds newly read data.

    wire full;                   // Indicates that the FIFO is completely full.
    wire empty;                  // Indicates that the FIFO contains no data.

    wire [COUNT_WIDTH-1:0] count; // Current number of stored FIFO words.

    integer errors;              // Counts the total number of verification failures.
    integer i;                   // Loop variable used in test sequences.


    // ========================================================================
    // 3. DEVICE UNDER TEST (DUT)
    // ========================================================================

    // Instantiate the FIFO module.
    // Parameter overrides configure the DUT according to the testbench.

    fpga_sync_read_fifo #(

        .DATA_WIDTH(DATA_WIDTH), // Configure FIFO data width.
        .DEPTH(DEPTH),           // Configure FIFO memory depth.
        .ADDR_WIDTH(ADDR_WIDTH), // Configure pointer address width.
        .COUNT_WIDTH(COUNT_WIDTH)// Configure occupancy counter width.

    ) DUT (

        .clk(clk),               // Connect testbench clock.
        .rst(rst),               // Connect synchronous reset.

        .wr_en(wr_en),           // Connect write request.
        .data_in(data_in),       // Connect input data bus.

        .rd_en(rd_en),           // Connect read request.
        .data_out(data_out),     // Connect registered output data.
        .data_valid(data_valid), // Monitor data-valid flag.

        .full(full),             // Monitor FIFO full status.
        .empty(empty),           // Monitor FIFO empty status.

        .count(count)            // Monitor FIFO occupancy.

    );

    // ========================================================================
    // 3b. MEMORY VIEW (DUT MEMORY MIRRORED INTO THE TESTBENCH)
    // ========================================================================
    // The FIFO memory stays inside the DUT (it must, for synthesis).
    // The testbench reads it through hierarchical references (DUT.memory)
    // and copies each word onto a testbench-level wire array.
    //
    // In Vivado XSIM: expand mem_view in the Objects window and add it to
    // the waveform to watch every memory location change.
    //
    // NOTE: The FIFO does not reset its memory array, so every location
    // shows X (unknown) at the start of simulation until it is written.

    genvar g;

    wire [DATA_WIDTH-1:0] mem_view [0:DEPTH-1];

    generate
        for (g = 0; g < DEPTH; g = g + 1) begin : MEM_MIRROR

            assign mem_view[g] = DUT.memory[g];

        end
    endgenerate

    // Pointer views, handy to display next to the memory in the waveform.
    wire [ADDR_WIDTH-1:0] wr_ptr_view = DUT.wr_ptr;
    wire [ADDR_WIDTH-1:0] rd_ptr_view = DUT.rd_ptr;
    

    // ========================================================================
    // 4. CLOCK GENERATION
    // ========================================================================
    // Clock period = 10 ns
    // Clock frequency = 100 MHz
    //
    // The clock toggles every 5 ns.
    // Both rising and falling edges are generated continuously.

    initial begin

        clk = 0;                 // Initialize clock to logic LOW.

        forever #5 clk = ~clk;   // Toggle clock every 5 ns.

    end


    // ========================================================================
    // 5. TASK: CHECK FIFO OCCUPANCY
    // ========================================================================
    // This task compares the actual FIFO count against the expected count.
    //
    // Case inequality (!==) also detects unknown X and Z values.

    task check_count;

        input [COUNT_WIDTH-1:0] expected_count;

        begin

            if (count !== expected_count) begin

                $display("ERROR: Count mismatch!");

                $display("Expected = %0d, Actual = %0d",
                         expected_count, count);

                errors = errors + 1; // Increment error counter.

            end

            else begin

                $display("PASS: FIFO count = %0d", count);

            end

        end

    endtask


    // ========================================================================
    // 6. TASK: CHECK FIFO OUTPUT DATA
    // ========================================================================
    // Compares the actual output data with the expected FIFO data.
    //
    // Case inequality detects mismatches as well as unknown values.

    task check_data;

        input [DATA_WIDTH-1:0] expected_data;

        begin

            if (data_out !== expected_data) begin

                $display("ERROR: Data mismatch!");

                $display("Expected = %h, Actual = %h",
                         expected_data, data_out);

                errors = errors + 1; // Record verification failure.

            end

            else begin

                $display("PASS: Data output = %h", data_out);

            end

        end

    endtask


    // ========================================================================
    // 6b. TASK: CHECK DATA_VALID FLAG
    // ========================================================================
    // Compares data_valid against its expected value (1 or 0).

    task check_valid;

        input expected_valid;

        begin

            if (data_valid !== expected_valid) begin

                $display("ERROR: data_valid mismatch!");

                $display("Expected = %b, Actual = %b",
                         expected_valid, data_valid);

                errors = errors + 1;

            end

            else begin

                $display("PASS: data_valid = %b", data_valid);

            end

        end

    endtask


    // ========================================================================
    // 7. TASK: WRITE ONE FIFO WORD
    // ========================================================================
    // Performs one write transaction.
    //
    // Operation:
    // 1. Wait for falling clock edge.
    // 2. Assert write enable.
    // 3. Apply input data.
    // 4. Wait for rising clock edge.
    // 5. Allow DUT nonblocking assignments to update.
    // 6. Deassert write enable.

    task fifo_write;

        input [DATA_WIDTH-1:0] value;

        begin

            @(negedge clk);      // Wait for falling clock edge.

            wr_en = 1;           // Enable FIFO write operation.

            data_in = value;     // Apply data to FIFO input.

            @(posedge clk);      // DUT samples write request here.

            #1;                  // Allow nonblocking assignments to settle.

            wr_en = 0;           // Disable write operation.

        end

    endtask


    // ========================================================================
    // 8. TASK: READ ONE FIFO WORD
    // ========================================================================
    // Performs one synchronous FIFO read transaction.
    //
    // Operation:
    // 1. Wait for falling clock edge.
    // 2. Assert read enable.
    // 3. Wait for rising clock edge.
    // 4. Allow registered output data to update.
    // 5. Deassert read enable.

    task fifo_read;

        begin

            @(negedge clk);      // Wait for falling clock edge.

            rd_en = 1;           // Enable FIFO read operation.

            @(posedge clk);      // DUT samples read request here.

            #1;                  // Allow registered data to update.

            rd_en = 0;           // Disable read operation.

        end

    endtask


    // ========================================================================
    // 9. MAIN TEST SEQUENCE
    // ========================================================================

    initial begin


        // --------------------------------------------------------------------
        // INITIALIZATION
        // --------------------------------------------------------------------

        rst     = 1;             // Assert active-high reset.

        wr_en   = 0;             // Disable write operation initially.

        rd_en   = 0;             // Disable read operation initially.

        data_in = 0;             // Initialize input data bus.

        errors  = 0;             // Clear error counter.


        // Display testbench information.

        $display("================================================");

        $display(" FPGA SYNCHRONOUS-READ FIFO TESTBENCH");

        $display(" Level 5 Verification");

        $display("================================================");


        // ====================================================================
        // TEST 1: SYNCHRONOUS RESET
        // ====================================================================

        $display("\nTEST 1: Synchronous Reset");


        repeat(2) @(posedge clk);
        // Keep reset asserted across two rising clock edges.

        #1;
        // Allow reset-related nonblocking assignments to settle.

        rst = 0;
        // Deassert reset after completing reset cycles.


        check_count(0);
        // Verify that FIFO occupancy has been cleared to zero.


        check_valid(0);
        // Verify that reset cleared the data-valid flag.


        if (empty && !full)

            $display("PASS: FIFO reset successful");

        else begin

            $display("ERROR: Reset status incorrect");

            errors = errors + 1;

        end


        // ====================================================================
        // TEST 2: BASIC WRITE OPERATION
        // ====================================================================

        $display("\nTEST 2: Basic Write Operation");


        fifo_write(8'h11);
        // Write hexadecimal 11 into the FIFO.

        check_count(1);
        // Verify that occupancy becomes 1.


        fifo_write(8'h22);
        // Write hexadecimal 22 into the FIFO.

        check_count(2);
        // Verify that occupancy becomes 2.


        fifo_write(8'h33);
        // Write hexadecimal 33 into the FIFO.

        check_count(3);
        // Verify that occupancy becomes 3.

        check_valid(0);
        // Writes alone must never raise data_valid.


        // ====================================================================
        // TEST 3: BASIC READ AND DATA ORDER
        // ====================================================================

        $display("\nTEST 3: FIFO Read and Data Ordering");


        fifo_read();
        // Read the oldest word stored in the FIFO.

        check_data(8'h11);
        // Verify that the first written word is read first.

        check_valid(1);
        // data_valid must be high right after an accepted read.

        check_count(2);
        // Verify that occupancy decreases to 2.


        fifo_read();
        // Read the next FIFO word.

        check_data(8'h22);
        // Verify that the second written word is returned.

        check_valid(1);

        check_count(1);
        // Verify that occupancy decreases to 1.


        fifo_read();
        // Read the final word in this sequence.

        check_data(8'h33);
        // Verify that the third written word is returned.

        check_valid(1);

        check_count(0);
        // Verify that occupancy becomes zero.


        // Let one idle clock edge pass (no read requested).
        @(posedge clk);
        #1;

        check_valid(0);
        // data_valid must fall when no read is accepted.

        check_data(8'h33);
        // data_out must hold its last value while idle.


        // ====================================================================
        // TEST 4: EMPTY CONDITION AND REJECTED READ
        // ====================================================================

        $display("\nTEST 4: Empty Condition");


        if (empty && count == 0)
        // Check both the empty flag and zero occupancy.

            $display("PASS: FIFO empty flag asserted");

        else begin

            $display("ERROR: FIFO empty flag incorrect");

            errors = errors + 1;

        end


        fifo_read();
        // Attempt a read while the FIFO is empty.


        check_count(0);
        // Verify that the rejected read does not change occupancy.

        check_valid(0);
        // A rejected read must NOT raise data_valid.


        if (empty)
        // FIFO must remain empty after an invalid read.

            $display("PASS: Read rejected while FIFO empty");

        else begin

            $display("ERROR: Empty condition failed");

            errors = errors + 1;

        end


        // ====================================================================
        // TEST 5: FILL FIFO COMPLETELY
        // ====================================================================

        $display("\nTEST 5: FIFO Full Condition");


        for (i = 0; i < DEPTH; i = i + 1)

            fifo_write(i);
            // Write sequential values into all FIFO memory locations.


        check_count(DEPTH);
        // Verify that occupancy equals the configured FIFO depth.


        if (full && !empty)
        // Full must be asserted and empty must be deasserted.

            $display("PASS: FIFO full flag asserted");

        else begin

            $display("ERROR: FIFO full flag incorrect");

            errors = errors + 1;

        end


        // ====================================================================
        // TEST 6: REJECTED WRITE WHEN FULL
        // ====================================================================

        $display("\nTEST 6: Rejected Write");


        fifo_write(8'hAA);
        // Attempt to write another word while the FIFO is full.
        // The FIFO should reject this operation.


        check_count(DEPTH);
        // Verify that occupancy remains equal to DEPTH.


        if (full)

            $display("PASS: FIFO rejected write while full");

        else begin

            $display("ERROR: Full protection failed");

            errors = errors + 1;

        end


        // ====================================================================
        // TEST 7: READ AFTER FULL
        // ====================================================================

        $display("\nTEST 7: Read After Full");


        fifo_read();
        // Read one word from the completely filled FIFO.


        check_data(8'h00);
        // The first word written was loop index zero.

        check_valid(1);


        check_count(DEPTH-1);
        // Verify that occupancy decreases from DEPTH to DEPTH-1.


        // ====================================================================
        // TEST 8: SIMULTANEOUS READ AND WRITE
        // ====================================================================

        $display("\nTEST 8: Simultaneous Read and Write");


        // At this point, FIFO contains DEPTH-1 words.
        // Both read and write operations should be accepted.


        @(negedge clk);
        // Align both requests before the next rising clock edge.


        wr_en = 1;
        // Request a write operation.

        rd_en = 1;
        // Request a read operation in the same clock cycle.

        data_in = 8'hF0;
        // Provide the new data word to be written.


        @(posedge clk);
        // FIFO processes both requests on the same rising edge.


        #1;
        // Allow nonblocking assignments to update.


        wr_en = 0;
        // Deassert write enable.

        rd_en = 0;
        // Deassert read enable.


        check_count(DEPTH-1);
        // One accepted write and one accepted read should preserve occupancy.

        check_valid(1);
        // The accepted read must raise data_valid.

        check_data(8'h01);
        // The word read here is the second word written (index 1).


        // ====================================================================
        // TEST 9: POINTER WRAPAROUND AND DATA ORDER
        // ====================================================================

        $display("\nTEST 9: Pointer Wraparound");


        // --------------------------------------------------------------------
        // DRAIN REMAINING FIFO CONTENTS
        // --------------------------------------------------------------------

        for (i = 0; i < DEPTH-1; i = i + 1)

            fifo_read();
            // Read all remaining FIFO words.


        check_count(0);
        // Verify that the FIFO occupancy becomes zero.


        if (empty)

            $display("PASS: FIFO empty after draining");

        else begin

            $display("ERROR: FIFO did not become empty");

            errors = errors + 1;

        end


        // --------------------------------------------------------------------
        // WRITE NEW DATA AFTER POINTER WRAPAROUND
        // --------------------------------------------------------------------

        fifo_write(8'hA1);
        // Write first new data word.

        fifo_write(8'hB2);
        // Write second new data word.

        fifo_write(8'hC3);
        // Write third new data word.


        // --------------------------------------------------------------------
        // VERIFY FIFO DATA ORDER
        // --------------------------------------------------------------------

        fifo_read();
        // Read the oldest word.

        check_data(8'hA1);
        // Verify that A1 is returned first.


        fifo_read();
        // Read the next word.

        check_data(8'hB2);
        // Verify that B2 is returned second.


        fifo_read();
        // Read the final word.

        check_data(8'hC3);
        // Verify that C3 is returned third.

        check_valid(1);


        check_count(0);
        // Confirm that FIFO is empty after all three reads.


        // ====================================================================
        // TEST 10: FINAL RESULT
        // ====================================================================

        $display("\n================================================");


        if (errors == 0)

            $display("ALL TESTS PASSED SUCCESSFULLY!");

        else

            $display("TESTBENCH FAILED: %0d ERRORS", errors);


        $display("================================================");


        $finish;
        // Stop the simulation after completing all tests.


    end


    // ========================================================================
    // 10. WAVEFORM / CONSOLE MONITORING
    // ========================================================================
    // $monitor automatically displays a new line whenever any monitored
    // signal changes.
    //
    // This is useful for observing FIFO behavior during simulation.

    initial begin

        $monitor("Time=%0t | rst=%b wr=%b rd=%b din=%h dout=%h valid=%b count=%0d full=%b empty=%b",

                 $time,       // Current simulation time.

                 rst,         // Reset signal.

                 wr_en,       // Write enable.

                 rd_en,       // Read enable.

                 data_in,     // FIFO input data.

                 data_out,    // FIFO registered output data.

                 data_valid,  // Data-valid flag.

                 count,       // FIFO occupancy counter.

                 full,        // FIFO full status.

                 empty);      // FIFO empty status.

    end


endmodule

